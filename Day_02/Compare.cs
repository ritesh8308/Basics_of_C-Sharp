using System;

namespace Day_02
{
    class Compare
    {
        static void Main(string[] args)
        {
            
            int x = 10;
            Console.WriteLine(x == 10);  // True
            Console.WriteLine(x != 10);  // False
            Console.WriteLine(x > 5);    // True
            Console.WriteLine(x < 5);    // False
            Console.WriteLine(x >= 10);  // True
            Console.WriteLine(x <= 9);   // False
            
        }
    }
}